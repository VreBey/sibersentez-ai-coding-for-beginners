// Feature string tables: each exports { en: {...}, tr: {...} } with the same keys in both languages. A key may not
// repeat a key of BASE or of another feature (test/i18n.test.mjs).
export const FEATURE_TABLES = Object.freeze({ actionsInApp: ACTIONS_IN_APP, terminal: TERMINAL, rosterFolders: ROSTER_FOLDERS, start: START, kit: KIT, usage: USAGE, github: GITHUB, aiStart: AI_START, attention: ATTENTION, cutaway: CUTAWAY, folders: FOLDERS, toolView: TOOL_VIEW, dock: DOCK, events: EVENTS, common: COMMON, shell: SHELL, guide: GUIDE, setupCheck: SETUP_CHECK, nav: NAV, promptHelp: PROMPT_HELP, runHint: RUN_HINT, changes: CHANGES, job: JOB, restore: RESTORE, workshop: WORKSHOP });

export const STRINGS = Object.freeze(
  Object.fromEntries(LANGUAGES.map((lang) => [lang, Object.freeze(Object.assign({}, BASE[lang], ...Object.values(FEATURE_TABLES).map((f) => f[lang] || {})))])),
);

// Mode -> string id of its name
export const MODE_KEYS = Object.freeze({ off: 'actionsModeOff', dry: 'actionsModeDry', live: 'actionsModeLive' });

let current = 'en';

const primary = (v) => (typeof v === 'string' ? v.trim().toLowerCase().split(/[-_]/)[0] : '');

// setting: the hub's language (?lang=); browser: navigator.language. A supported setting wins, then a Turkish
// browser, else English.
export function pickLanguage({ setting, browser } = {}) {
  const s = primary(setting);
  if (LANGUAGES.includes(s)) return s;
  return primary(browser) === 'tr' ? 'tr' : 'en';
}

export function setLanguage(lang) {
  current = LANGUAGES.includes(lang) ? lang : 'en';
  return current;
}

export function language() {
  return current;
}

// Text of an id in the current language (English if missing); unknown placeholders stay as they are
export function t(key, values = {}) {
  const text = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return String(text).replace(/\{(\w+)\}/g, (m, k) => (Object.hasOwn(values, k) ? String(values[k]) : m));
}

// Name of an action mode ('off' | 'dry' | 'live'); anything else reads as off
export function modeName(mode) {
  return t(MODE_KEYS[mode] || MODE_KEYS.off);
}

// What the mode means for the person, next to its name in the header indicator (review U11)
const STATE_KEYS = Object.freeze({ off: 'actionsStateOff', dry: 'actionsStateDry', live: 'actionsStateLive' });
export function stateName(mode) {
  return t(STATE_KEYS[mode] || STATE_KEYS.off);
}
// The indicator's mode: its name and what it means ("Off · only watches")
export const indicatorMode = (mode) => `${modeName(mode)} · ${stateName(mode)}`;
